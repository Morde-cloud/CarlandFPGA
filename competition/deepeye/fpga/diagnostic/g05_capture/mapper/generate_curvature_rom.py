"""Generate exact floors from rigorous rational Machin/alternating-series bounds."""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ENUM_SHA = 'a52f3631d94d396c7da769f82a09e70d55c765b0c2651de27476e644c486573e'
LOCK_SHA = 'c229834bfc2292f5fe4411fc9f12c68487008f9d1adaf31f0144ee7a98173804'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def atan_bounds(denominator, terms):
    x = Fraction(1, denominator)
    partial = sum(((-1)**k * x**(2*k+1) / (2*k+1) for k in range(terms)), Fraction(0))
    next_partial = partial + (-1)**terms * x**(2*terms+1) / (2*terms+1)
    return min(partial, next_partial), max(partial, next_partial)


def rational(value):
    return {'numerator': str(value.numerator), 'denominator': str(value.denominator)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--enums', type=Path, required=True)
    ap.add_argument('--assignment', type=Path, required=True)
    ap.add_argument('--lock', type=Path, required=True)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    assert sha(args.enums) == ENUM_SHA, 'A enums input hash mismatch'
    contract = json.loads(args.lock.read_text(encoding='utf-8-sig'))
    lock_hash = hashlib.sha256(json.dumps(contract['requirements'], ensure_ascii=False,
        sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    assert lock_hash == LOCK_SHA, 'fixed H01-H15 hash mismatch'
    assert [r['id'] for r in contract['requirements']] == [f'H{i:02d}' for i in range(1, 16)]
    enum = json.loads(args.enums.read_text(encoding='utf-8-sig'))
    assert enum['transport_profile_id'] == {'fast_9600': 1, 'stress_300': 2}

    a_lo, a_hi = atan_bounds(5, 80)
    b_lo, b_hi = atan_bounds(239, 30)
    exact_lo, exact_hi = 16*a_lo-4*b_hi, 16*a_hi-4*b_lo
    scale = 10**100
    scaled_lo, scaled_hi = exact_lo*scale, exact_hi*scale
    lo_integer = scaled_lo.numerator // scaled_lo.denominator
    hi_integer = -(-scaled_hi.numerator // scaled_hi.denominator)
    lo, hi = Fraction(lo_integer, scale), Fraction(hi_integer, scale)
    assert 3 < lo < hi < 4 and lo <= exact_lo <= exact_hi <= hi
    rows = []
    sv = ['// Generated by generate_curvature_rom.py; exact, bounded pi floors.',
          'case ({profile_id, speed_code})']
    for profile, divisor in ((1, 80), (2, 10000)):
        for code in range(21):
            q = Fraction(code*90000, divisor)
            lower, upper = (q/hi)**2, (q/lo)**2
            lower_floor = lower.numerator // lower.denominator
            upper_floor = upper.numerator // upper.denominator
            assert lower_floor == upper_floor, (profile, code, 'ambiguous floor')
            rows.append({'profile_id': profile, 'speed_code': code,
                'velocity_m_per_s': rational(Fraction(code, divisor)),
                'squared_lower': rational(lower), 'squared_upper': rational(upper),
                'lower_floor': lower_floor, 'upper_floor': upper_floor,
                'curvature_limit': lower_floor})
            sv.append(f"    16'h{profile:02x}{code:02x}: curvature_limit = 64'd{lower_floor};")
    sv += ["    default: curvature_limit = 64'd0;", 'endcase', '']
    root = Path(__file__).resolve().parent
    document = {'schema': 1, 'task': 'DEEPEYE-IMPLEMENTATION-20261014/v1',
        'work_id': 'B-G05-GUARD-MAPPER-20261026-59-v1',
        'requirements_sha256': LOCK_SHA, 'requirement_ids': [f'H{i:02d}' for i in range(1,16)],
        'contract_commit': 'f5989cd5defce561f9ba98e6b18fc2682945f0a2',
        'frozen_design': '1011259415a0916054eb580687612580bc1e5f09',
        'source_hashes': {name: sha(root/name) for name in
            ('generate_curvature_rom.py', 'deepeye_g05_command_map.sv')},
        'inputs': {name: {'path': str(path.resolve()), 'sha256': sha(path)} for name, path in
            (('enums', args.enums), ('assignment', args.assignment), ('contract', args.lock))},
        'proof': 'Machin pi=16*atan(1/5)-4*atan(1/239); alternating decreasing series bounds each atan between N and N+1 partial sums. Sign-aware combination then outward rational rounding. For nonnegative q, (q/pi_upper)^2 <= (q/pi)^2 <= (q/pi_lower)^2. Identical exact endpoint floors certify each constant.',
        'atan_terms': {'1/5': 80, '1/239': 30},
        'pi_lower': rational(lo), 'pi_upper': rational(hi),
        'pi_lower_decimal': f'{lo_integer//scale}.{lo_integer%scale:0100d}',
        'pi_upper_decimal': f'{hi_integer//scale}.{hi_integer%scale:0100d}',
        'row_count': len(rows), 'rows': rows}
    outputs = {'curvature_limits.json': json.dumps(document, indent=2, ensure_ascii=False)+'\n',
               'deepeye_g05_curvature_rom.svh': '\n'.join(sv)}
    for name, contents in outputs.items():
        payload = contents.encode('utf-8')
        if args.check:
            assert (root/name).read_bytes() == payload, f'{name} differs'
        else:
            with (root/name).open('xb') as stream:
                stream.write(payload)
    print(json.dumps({'status': 'verified' if args.check else 'generated', 'rows': len(rows),
        'pi_lower': document['pi_lower_decimal'], 'pi_upper': document['pi_upper_decimal'],
        'outputs': {name: sha(root/name) for name in outputs}}, indent=2))


if __name__ == '__main__':
    main()
