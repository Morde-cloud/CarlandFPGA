reg [31:0] post_out_tick;
reg [5:0] post_out_len;
reg [255:0] post_out_payload;
reg post_receiving;
reg post_error_event;
reg [1:0] post_error_code;
reg [31:0] post_stat_bytes;
reg [31:0] post_stat_frames;
reg [31:0] post_stat_retired;
reg [31:0] post_stat_version;
reg [31:0] post_stat_length;
reg [31:0] post_stat_crc;
reg [31:0] post_stat_aborted;
deepeye_wire_parser #(.STAT_W(STAT_W)) dut(.*);
