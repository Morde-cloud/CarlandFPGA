eq("post_out_payload",(out_valid?out_payload:0),post_out_payload);
eq("post_receiving",receiving,post_receiving);
eq("post_error_event",error_event,post_error_event);
eq("post_error_code",error_code,post_error_code);
eq("post_stat_bytes",stat_bytes,post_stat_bytes);
eq("post_stat_frames",stat_frames,post_stat_frames);
eq("post_stat_retired",stat_retired,post_stat_retired);
eq("post_stat_version",stat_version,post_stat_version);
eq("post_stat_length",stat_length,post_stat_length);
eq("post_stat_crc",stat_crc,post_stat_crc);
eq("post_stat_aborted",stat_aborted,post_stat_aborted);
end else if(!$feof(fd))$fatal(1,"malformed vector row");
end
$fclose(fd);
$display("MAIN_STATS cycles=%0d checks=%0d",cycles,checks);
$display("MAIN_PASS");$finish;end
