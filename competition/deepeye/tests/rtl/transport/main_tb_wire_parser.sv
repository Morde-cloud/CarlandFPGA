eq("pre_stat_retired",stat_retired,pre_stat_retired);
eq("pre_stat_version",stat_version,pre_stat_version);
eq("pre_stat_length",stat_length,pre_stat_length);
eq("pre_stat_crc",stat_crc,pre_stat_crc);
eq("pre_stat_aborted",stat_aborted,pre_stat_aborted);
@(posedge clk);#1;cycles++;
eq("post_in_ready",in_ready,post_in_ready);
eq("post_out_valid",out_valid,post_out_valid);
eq("post_out_type",(out_valid?out_type:0),post_out_type);
eq("post_out_epoch",(out_valid?out_epoch:0),post_out_epoch);
eq("post_out_seq",(out_valid?out_seq:0),post_out_seq);
eq("post_out_tick",(out_valid?out_tick:0),post_out_tick);
