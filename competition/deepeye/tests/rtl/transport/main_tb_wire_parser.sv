parameter integer STAT_W=32;
localparam integer SW=(STAT_W<2)?2:((STAT_W>32)?32:STAT_W);
reg clk=0;always #5 clk=~clk;
reg rst;
reg cancel;
reg in_valid;
reg [7:0] in_data;
reg out_ready;
wire in_ready;
wire out_valid;
wire [7:0] out_type;
wire [7:0] out_epoch;
wire [15:0] out_seq;
wire [31:0] out_tick;
