integer fd,got,cycles=0,checks=0;
task automatic eq(input string field,input logic[255:0] actual,input logic[255:0] expected);
begin checks++;if(actual!==expected)begin $display("MAIN_MISMATCH cycle=%0d field=%s got=%0h expected=%0h",cycles,field,actual,expected);$fatal(1,"main numeric mismatch");end end endtask
initial begin
rst=1;
cancel=0;
in_valid=0;
in_data=0;
out_ready=0;
$display("MAIN_BEGIN kind=wire_parser stat=%0d",STAT_W);
fd=$fopen("vectors.hex","r");if(!fd)$fatal(1,"missing vectors");
while(!$feof(fd))begin
got=$fscanf(fd,"%h\n",row);if(got==1)begin
@(negedge clk);{rst,cancel,in_valid,in_data,out_ready,pre_in_ready,pre_out_valid,pre_out_type,pre_out_epoch,pre_out_seq,pre_out_tick,pre_out_len,pre_out_payload,pre_receiving,pre_error_event,pre_error_code,pre_stat_bytes,pre_stat_frames,pre_stat_retired,pre_stat_version,pre_stat_length,pre_stat_crc,pre_stat_aborted,post_in_ready,post_out_valid,post_out_type,post_out_epoch,post_out_seq,post_out_tick,post_out_len,post_out_payload,post_receiving,post_error_event,post_error_code,post_stat_bytes,post_stat_frames,post_stat_retired,post_stat_version,post_stat_length,post_stat_crc,post_stat_aborted}=row;#1;
eq("pre_in_ready",in_ready,pre_in_ready);
