`timescale 1ns/1ps
// Main vector checker: all expectations come from frozen Python public-history reference.
module main_tb_wire_serializer;
parameter integer STAT_W=32;
localparam integer SW=(STAT_W<2)?2:((STAT_W>32)?32:STAT_W);
reg clk=0;always #5 clk=~clk;
reg rst;
reg cancel;
reg cfg_valid;
reg [7:0] cfg_type;
reg [7:0] cfg_epoch;
reg [15:0] cfg_seq;
reg [31:0] cfg_tick;
reg [5:0] cfg_len;
reg p_valid;
reg [7:0] p_data;
reg p_last;
reg out_ready;
wire cfg_ready;
wire p_ready;
wire out_valid;
wire [7:0] out_data;
wire out_last;
wire [5:0] out_count;
wire busy;
wire receiving;
wire faulted;
wire fault_event;
wire [1:0] fault_code;
wire [SW-1:0] stat_admitted;
wire [SW-1:0] stat_sent;
wire [SW-1:0] stat_aborted;
wire [SW-1:0] stat_faults;
reg pre_cfg_ready;
reg pre_p_ready;
reg pre_out_valid;
reg [7:0] pre_out_data;
reg pre_out_last;
reg [5:0] pre_out_count;
reg pre_busy;
reg pre_receiving;
reg pre_faulted;
reg pre_fault_event;
reg [1:0] pre_fault_code;
reg [31:0] pre_stat_admitted;
reg [31:0] pre_stat_sent;
reg [31:0] pre_stat_aborted;
reg [31:0] pre_stat_faults;
reg post_cfg_ready;
reg post_p_ready;
reg post_out_valid;
reg [7:0] post_out_data;
reg post_out_last;
reg [5:0] post_out_count;
reg post_busy;
reg post_receiving;
reg post_faulted;
reg post_fault_event;
reg [1:0] post_fault_code;
reg [31:0] post_stat_admitted;
reg [31:0] post_stat_sent;
reg [31:0] post_stat_aborted;
reg [31:0] post_stat_faults;
deepeye_wire_serializer #(.STAT_W(STAT_W)) dut(.*);
reg [387:0] row;
integer fd,got,cycles=0,checks=0;
task automatic eq(input string field,input logic[255:0] actual,input logic[255:0] expected);
begin checks++;if(actual!==expected)begin $display("MAIN_MISMATCH cycle=%0d field=%s got=%0h expected=%0h",cycles,field,actual,expected);$fatal(1,"main numeric mismatch");end end endtask
initial begin
rst=1;
cancel=0;
cfg_valid=0;
cfg_type=0;
cfg_epoch=0;
cfg_seq=0;
cfg_tick=0;
cfg_len=0;
p_valid=0;
p_data=0;
p_last=0;
out_ready=0;
$display("MAIN_BEGIN kind=wire_serializer stat=%0d",STAT_W);
fd=$fopen("vectors.hex","r");if(!fd)$fatal(1,"missing vectors");
while(!$feof(fd))begin
got=$fscanf(fd,"%h\n",row);if(got==1)begin
@(negedge clk);{rst,cancel,cfg_valid,cfg_type,cfg_epoch,cfg_seq,cfg_tick,cfg_len,p_valid,p_data,p_last,out_ready,pre_cfg_ready,pre_p_ready,pre_out_valid,pre_out_data,pre_out_last,pre_out_count,pre_busy,pre_receiving,pre_faulted,pre_fault_event,pre_fault_code,pre_stat_admitted,pre_stat_sent,pre_stat_aborted,pre_stat_faults,post_cfg_ready,post_p_ready,post_out_valid,post_out_data,post_out_last,post_out_count,post_busy,post_receiving,post_faulted,post_fault_event,post_fault_code,post_stat_admitted,post_stat_sent,post_stat_aborted,post_stat_faults}=row;#1;
eq("pre_cfg_ready",cfg_ready,pre_cfg_ready);
eq("pre_p_ready",p_ready,pre_p_ready);
eq("pre_out_valid",out_valid,pre_out_valid);
eq("pre_out_data",(out_valid?out_data:0),pre_out_data);
eq("pre_out_last",(out_valid?out_last:0),pre_out_last);
eq("pre_out_count",out_count,pre_out_count);
eq("pre_busy",busy,pre_busy);
eq("pre_receiving",receiving,pre_receiving);
eq("pre_faulted",faulted,pre_faulted);
eq("pre_fault_event",fault_event,pre_fault_event);
eq("pre_fault_code",fault_code,pre_fault_code);
eq("pre_stat_admitted",stat_admitted,pre_stat_admitted);
eq("pre_stat_sent",stat_sent,pre_stat_sent);
eq("pre_stat_aborted",stat_aborted,pre_stat_aborted);
eq("pre_stat_faults",stat_faults,pre_stat_faults);
@(posedge clk);#1;cycles++;
eq("post_cfg_ready",cfg_ready,post_cfg_ready);
eq("post_p_ready",p_ready,post_p_ready);
eq("post_out_valid",out_valid,post_out_valid);
eq("post_out_data",(out_valid?out_data:0),post_out_data);
eq("post_out_last",(out_valid?out_last:0),post_out_last);
eq("post_out_count",out_count,post_out_count);
eq("post_busy",busy,post_busy);
eq("post_receiving",receiving,post_receiving);
eq("post_faulted",faulted,post_faulted);
eq("post_fault_event",fault_event,post_fault_event);
eq("post_fault_code",fault_code,post_fault_code);
eq("post_stat_admitted",stat_admitted,post_stat_admitted);
eq("post_stat_sent",stat_sent,post_stat_sent);
eq("post_stat_aborted",stat_aborted,post_stat_aborted);
eq("post_stat_faults",stat_faults,post_stat_faults);
end else if(!$feof(fd))$fatal(1,"malformed vector row");
end
$fclose(fd);
$display("MAIN_STATS cycles=%0d checks=%0d",cycles,checks);
$display("MAIN_PASS");$finish;end
endmodule
